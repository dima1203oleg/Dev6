export interface RegistrySourceItem {
  id: string;
  name: string;
  authority: string;
  accessLevel: "FREE_AUTO" | "FREE_API_KEY" | "FREE_WITH_APPROVAL" | "MANUAL" | "PAID_API" | "RESTRICTED";
  automationLevel: "A0" | "A0*" | "A1" | "A1*" | "A1-A2" | "A3" | "A3*" | "A3+" | "A4" | "A4*" | "A4-A5" | "A6";
  entities: string[];
  priority: "P0" | "P1" | "P2" | "P3" | "P4" | "P-RESEARCH";
  contour: "A" | "B" | "C" | "D"; // A: Ukrainian/State, B: International, C: Cyber/OSINT, D: Paid/Restricted
  officialUrl: string;
  format: string;
  updateFrequency: string;
  status: "HEALTHY" | "DEGRADED" | "UNAVAILABLE" | "DISABLED" | "CANDIDATE";
  bv: number; // Business Value (1-5)
  ca: number; // Coverage & Relevance (1-5)
  aut: number; // Automation Degree (1-5)
  free: number; // Openness & Zero-Cost (1-5)
  du: number; // Data Uniqueness (1-5)
  ec: number; // Entity Connectivity (1-5)
  ic: number; // Integration Complexity Penalty (0-5)
  lr: number; // Legal Risk Penalty (0-5)
  cost: number; // Financial Cost Penalty (0-5)
  priorityScore?: number;
  automaticAction?: "AUTO-INTEGRATE" | "RESEARCH/INTEGRATE" | "HUMAN GATE" | "FALLBACK" | "LEGAL REVIEW" | "DISCOVERY ONLY";
  description?: string;
  recordsCountEstimate?: number;
}

// Helper to compute Priority Score: BV + CA + AUT + FREE + DU + EC - IC - LR - COST
export function calculatePriorityScore(item: Omit<RegistrySourceItem, "priorityScore" | "automaticAction">): RegistrySourceItem {
  const score = item.bv + item.ca + item.aut + item.free + item.du + item.ec - item.ic - item.lr - item.cost;
  
  let automaticAction: RegistrySourceItem["automaticAction"] = "DISCOVERY ONLY";
  if (item.accessLevel === "RESTRICTED") {
    automaticAction = "LEGAL REVIEW";
  } else if (item.accessLevel === "PAID_API") {
    automaticAction = "FALLBACK";
  } else if (item.accessLevel === "FREE_WITH_APPROVAL" || item.automationLevel.startsWith("A3")) {
    automaticAction = "HUMAN GATE";
  } else if (score >= 22 && (item.accessLevel === "FREE_AUTO" || item.automationLevel.startsWith("A0"))) {
    automaticAction = "AUTO-INTEGRATE";
  } else if (score >= 18) {
    automaticAction = "RESEARCH/INTEGRATE";
  } else {
    automaticAction = "DISCOVERY ONLY";
  }

  return {
    ...item,
    priorityScore: score,
    automaticAction
  };
}

